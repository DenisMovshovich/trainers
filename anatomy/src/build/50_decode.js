function explainAttr(a){
  for(const [rx,name,tpl] of ATTRS){
    const m = a.match(rx);
    if(m) return {name, text: tpl.replace(/\$1/g, m[1]!==undefined ? m[1] : "")};
  }
  return {name:a.replace(/^\[|\]$/g,"").split("(")[0], text:"Атрибут NUnit или .NET."};
}

