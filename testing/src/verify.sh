#!/bin/bash
# Полная проверка: движок → ответы → негативный контроль → целостность → браузер → раскладка
set -e
cd "$(dirname "$0")"
echo "═══ 1. движок техник тест-дизайна ════════════════════"
./runt.sh | tail -2
echo
