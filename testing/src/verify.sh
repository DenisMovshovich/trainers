node check.js
echo
echo "═══ 3. негативный контроль ═══════════════════════════"
node check.js --neg
echo
echo "═══ 4. целостность содержания, глоссария и SVG ═══════"
node integrity.js
echo
echo "═══ 5. сборка ════════════════════════════════════════"
./assemble.sh
echo
echo "═══ 6. браузер (Chromium, 5 сочетаний темы и ширины) ═"
node browser.mjs
echo
echo "═══ 7. глоссарий не уходит под панель инструментов ═══"
node fit.mjs
