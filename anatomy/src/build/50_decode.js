function decodeSelector(body){
  const out = {kind:null, sel:null, notes:[], chain:[]};
  if(!body) return out;

  const role = body.match(/GetByRole\(AriaRole\.(\w+)[\s\S]*?Name\s*=\s*"([^"]*)"/);
  if(role){
    out.kind = "role";
    out.sel = 'GetByRole(' + role[1] + ', Name = "' + role[2] + '")';
    out.notes.push(["по роли и имени", "Ищет элемент с ролью <b>"+role[1].toLowerCase()+"</b> и доступным именем «"+role[2]+"». Доступное имя сопоставляется <b>без учёта регистра</b> и собирается из текста, aria-label и подписи — поэтому работает там, где точное совпадение текста не находит ничего."]);
    return out;
  }
  const roleBare = body.match(/GetByRole\(AriaRole\.(\w+)\s*\)/);
  if(roleBare){
    out.kind = "role";
    out.sel = "GetByRole(" + roleBare[1] + ")";
    out.notes.push(["по роли", "Ищет элемент с ролью <b>"+roleBare[1].toLowerCase()+"</b> без уточнения имени. Уместно там, где разметка меняется между сессиями и важно лишь то, что это кнопка."]);
    if(/\.First\b/.test(body)) out.chain.push([".First", "Берётся первая подходящая. Здесь это осознанно: у баннера кук бывает то одна кнопка «Close», то пара «Accept all» / «Reject all», а закрыть достаточно любую."]);
    const sc = body.match(/^(\w+)\.GetByRole/);
    if(sc && !/^(Page|_page)$/.test(sc[1])) out.notes.push(["вложенный поиск", "Ищет внутри <code>"+esc(sc[1])+"</code>."]);
    return out;
  }
  const loc = body.match(/Locator\(\s*(\$?)"((?:[^"\\]|\\.)*)"/);
  if(!loc) return out;
  let s = loc[2].replace(/\\"/g, '"');
  out.sel = s;
  const interpolated = loc[1] === "$";

  const scoped = body.match(/^(\w+)\.Locator\(/);
  if(scoped && !/^(Page|_page)$/.test(scoped[1]))
    out.notes.push(["вложенный поиск", "Ищет внутри <code>"+esc(scoped[1])+"</code>, а не по всей странице. Сужение области — главный способ не поймать одноимённый элемент в другом месте."]);

  if(interpolated)
    out.notes.push(["строка с подстановкой", "Селектор собирается из параметра метода. Один такой локатор заменяет десятки почти одинаковых."]);

  if(/^xpath=/.test(s) || /^\/\//.test(s) || /^\.\/\//.test(s)){
    out.kind = "xpath";
    XPR.forEach(([rx, pair])=>{ if(rx.test(s)) out.notes.push(pair); });
    if(!out.notes.length) out.notes.push(["XPath", "Путь по дереву документа. Гибче CSS, но обычно сильнее привязан к структуре страницы."]);
  } else {
    out.kind = "css";
    CSSR.forEach(([rx, fn])=>{
      rx.lastIndex = 0; let m, seen = new Set();
      while((m = rx.exec(s))){ const [k,v] = fn(m); if(!seen.has(k)){ seen.add(k); out.notes.push([k,v]); } if(!rx.global) break; }
    });
    if(/\s/.test(s.trim()) && !out.notes.some(n=>n[0]==="вложенный поиск"))
      out.notes.push(["потомок", "Пробел означает «внутри»: правая часть ищется среди потомков левой."]);
    if(!out.notes.length) out.notes.push(["CSS-селектор", "Обычный CSS-селектор по тегу или классу."]);
  }

  if(/\.First\b/.test(body)) out.chain.push([".First", "Берётся первый из найденных. Нужен там, где элементов заведомо несколько: без него Playwright в строгом режиме падает с ошибкой неоднозначности."]);
  if(/\.Nth\(/.test(body)) out.chain.push([".Nth(n)", "Элемент по порядковому номеру. Хрупко, если порядок задаёт бэкенд."]);
  if(/HasTextRegex/.test(body)) out.chain.push(["HasTextRegex", "Дополнительный фильтр по тексту регулярным выражением. Якоря ^ и $ дают точное совпадение — так «1» не совпадает с «11»."]);
  if(/HasText\s*=/.test(body)) out.chain.push(["HasText", "Фильтр по вхождению текста."]);
  return out;
}

