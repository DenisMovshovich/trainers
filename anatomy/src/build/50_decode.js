function memberKindText(m, cls, file){
  const isLoc = m.t === "ILocator";
  if(m.k === "ctor") return "Конструктор. Вызывается при создании объекта; в page object обычно передаёт страницу и базовый адрес в базовый класс.";
  if(isLoc && m.k === "prop") return "Локатор — <b>рецепт поиска</b>, а не найденный элемент. Тело со стрелкой означает, что поиск выполняется заново при каждом обращении, поэтому устаревших ссылок не возникает даже после перерисовки страницы.";
  if(isLoc && m.k === "method") return "Локатор с параметром: тот же рецепт поиска, но часть селектора приходит извне.";
  if(m.k === "field" && m.m.includes("const")) return "Константа. Значение подставляется при компиляции.";
  if(m.k === "field" && /null!$/.test(m.b)) return "Поле фикстуры. <code>null!</code> — обещание компилятору, что значение появится: оно присваивается в [SetUp], о чём компилятор знать не может.";
  if(m.k === "field") return "Поле класса — хранит состояние объекта.";
  if(m.a.some(a=>a.startsWith("[Test]"))) return "Тестовый случай.";
  if(m.a.some(a=>a.startsWith("[SetUp]"))) return "Подготовка перед каждым тестом фикстуры.";
  if(m.k === "method" && m.m.includes("private")) return "Вспомогательный метод фикстуры: общий путь до нужного шага или общая проверка. Вынесен сюда, а не в page object, потому что описывает сценарий, а не страницу.";
  if(m.k === "method" && /^Task/.test(m.t)) return "Асинхронное действие над страницей.";
  if(m.k === "prop") return "Свойство.";
  return "Метод.";
}

/* ---------------- подсветка кода ---------------- */
function hiCs(s){
  s = esc(s);
  s = s.replace(/(\/\/[^\n]*)/g,'<span class="cm">$1</span>');
  s = s.replace(/("(?:[^"\\]|\\.)*")/g,'<span class="str">$1</span>');
  s = s.replace(/\b(public|private|internal|protected|static|readonly|const|async|await|override|class|record|new|return|var|string|int|bool|void|Task|ILocator|IPage|true|false|null)\b/g,'<span class="kw">$1</span>');
  s = s.replace(/\b(\d+)\b/g,'<span class="num">$1</span>');
  return s;
}

/* Обёртка над другим членом: public ILocator EmailFieldLocator => EmailField; */
function aliasTarget(body){
  if(!body) return null;
  const c = String(body).trim().match(/^(Header|NavBar|Footer)\.([A-Za-z_]\w*)\s*$/);
  if(c) return {comp:c[1], name:c[2], tail:""};
  const m = String(body).trim().match(/^([A-Za-z_]\w*)((?:\.(?:First|Last)|\.Nth\([^)]*\))*)\s*$/);
  if(!m) return null;
  if(/^(Page|_page|true|false|null|string)$/.test(m[1])) return null;
  return {name:m[1], tail:m[2]||""};
}
